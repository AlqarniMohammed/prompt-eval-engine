"""Matrix generator: reads per-suite specs from datasets/graded-specs/,
composes cells across the declared axes (full product up to
graded.max_cells_per_suite, greedy pairwise reduction above it), reserves the
graded.holdout fraction as tagged holdout cells, and writes LITERAL cases to
datasets/graded/<suite>.yaml — never YAML arrays (the cartesian trap), every
axis value a plain var. Regeneration is byte-deterministic (guarded by
tests/test_matrix_parity.py); holdout cells are hash-ranked, not positional,
so the reserved set is spread across the matrix instead of always parking in
the last corner of every axis."""

from __future__ import annotations

import hashlib

import yaml

from src import config


def product(axes: list[dict]) -> list[list[dict]]:
    cells: list[list[dict]] = [[]]
    for axis in axes:
        cells = [cell + [{"axis": axis["name"], "value": v}] for cell in cells for v in axis["values"]]
    return cells


def pairwise_reduce(axes: list[dict]) -> list[list[dict]]:
    """Greedy pairwise reduction: keep cells until every value-pair is covered."""
    all_cells = product(axes)
    pair_key = lambda a, b: f'{a["axis"]}={a["value"]["id"]}|{b["axis"]}={b["value"]["id"]}'
    needed = set()
    for i in range(len(axes)):
        for j in range(i + 1, len(axes)):
            for a in axes[i]["values"]:
                for b in axes[j]["values"]:
                    needed.add(pair_key({"axis": axes[i]["name"], "value": a},
                                        {"axis": axes[j]["name"], "value": b}))
    chosen = []
    for cell in all_cells:
        if not needed:
            break
        pairs = [pair_key(cell[i], cell[j]) for i in range(len(cell)) for j in range(i + 1, len(cell))]
        if any(p in needed for p in pairs):
            chosen.append(cell)
            needed -= set(pairs)
    return chosen


def generate(spec_path, out_dir=None) -> dict:
    spec = yaml.safe_load(spec_path.read_text())
    if not spec.get("suite") or not config.suite_by_id(spec["suite"]):
        raise ValueError(f'{spec_path}: "suite" missing or not declared in eval_config.yaml suites')
    axes = [{"name": name, "values": values} for name, values in (spec.get("axes") or {}).items()]
    if not axes:
        raise ValueError(f"{spec_path}: no axes declared")

    graded = config.get().get("graded", {})
    max_cells = graded.get("max_cells_per_suite", 8)
    holdout_fraction = graded.get("holdout", 0.25)

    cells = product(axes)
    if len(cells) > max_cells:
        cells = pairwise_reduce(axes)
    note = None
    if len(cells) > max_cells:
        note = (f'{spec["suite"]} pairwise still {len(cells)} cells (cap {max_cells}) — '
                "keeping pairwise (coverage beats the cap)")

    # Deterministic, position-free reservation: rank full cell ids by their
    # sha256 and reserve the first n. Byte-identical on regeneration (no RNG
    # state), but free of the old every-Nth stride that made the holdout
    # always the last value of every axis (audit finding 6).
    n_holdout = round(len(cells) * holdout_fraction) if holdout_fraction > 0 else 0
    full_ids = [f'{spec["suite"]}·{"-".join(c["value"]["id"] for c in cell)}' for cell in cells]
    holdout_ids = set(sorted(full_ids,
                             key=lambda cid: hashlib.sha256(cid.encode()).hexdigest())[:n_holdout])

    cases = []
    for cell in cells:
        cell_id = "-".join(c["value"]["id"] for c in cell)
        variables = {**(spec.get("base") or {}), "suite": spec["suite"], "cell": f'{spec["suite"]}·{cell_id}'}
        probe = ""
        for c in cell:
            if c["value"].get("probe"):
                probe += ("\n" if probe else "") + c["value"]["probe"]
            variables.update(c["value"].get("vars") or {})
            variables[f'axis{c["axis"][0].upper()}{c["axis"][1:]}'] = c["value"]["id"]
        if probe:
            variables["probe"] = probe
        variables["holdout"] = "true" if variables["cell"] in holdout_ids else "false"
        cases.append({
            "description": f'{spec["suite"]} · {cell_id}' + (" [holdout]" if variables["holdout"] == "true" else ""),
            "vars": variables,
            "assert": spec.get("contracts") or [],
        })

    out_dir = out_dir or config.graded_dir()
    out_dir.mkdir(parents=True, exist_ok=True)
    n_holdout = sum(1 for c in cases if c["vars"]["holdout"] == "true")
    header = (
        f"# GENERATED by gen_matrix from {spec_path.name} — do not hand-edit.\n"
        f"# {len(cases)} cells ({n_holdout} holdout, excluded from iteration runs).\n"
    )
    out_file = out_dir / f'{spec["suite"]}.yaml'
    out_file.write_text(header + yaml.safe_dump(cases, width=100, sort_keys=False, allow_unicode=True))
    return {"suite": spec["suite"], "cells": len(cases), "holdout": n_holdout,
            "out": out_file, "note": note}
